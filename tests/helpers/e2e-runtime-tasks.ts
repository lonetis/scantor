// Task folders generated at run time for the e2e runtime specs (templates, scheduler, retries, files, workers,
// placement, breaker, privileged, backpressure, limits). They are small Python tasks on the base image (`COPY . .`,
// no requirements), so they build in seconds and pass the type check of every publish. Each kind reaches a mechanism
// the example and fixture tasks cannot reach on their own: unwrapped templates that echo their analysis configs, a
// custom schedule that wraps a template and fails in controlled ways, a probe whose run ends in every documented way,
// a worker that never gets a connector process ready, and a privileged task.

const DOCKERFILE = `ARG SCANTOR_BASE
FROM \${SCANTOR_BASE}
COPY . .
`

const DOCKERIGNORE = `__pycache__/
.scantor/
`

const PYRIGHT = `{
  "typeCheckingMode": "standard",
  "pythonVersion": "3.14"
}
`

/** The templates a generated `tpl-*` task passes unwrapped. */
export type UnwrappedTemplate = 'list' | 'range' | 'tranco' | 'crux' | 'cidr'

/** A template passed unwrapped: the scheduler runs it natively; `run` returns the analysis config it received. */
function templateTask(template: UnwrappedTemplate): string {
  return `"""Generated by the e2e runtime specs: the template ${template} unwrapped; run returns its analysis config."""

import asyncio

from pydantic import BaseModel, Field

import scantor
from scantor import templates


class TaskConfig(scantor.Config):
    sleep_seconds: float = Field(default=0, ge=0, le=600, description="Pause in every run (cancellable).")


class Result(BaseModel):
    config: dict[str, object]


async def run(
    ctx: scantor.Context, analysis_config: templates.${template}.AnalysisConfig, task_config: TaskConfig
) -> Result:
    await asyncio.sleep(task_config.sleep_seconds)
    return Result(config=analysis_config.model_dump(mode="json", by_alias=True))


task = scantor.Task(task_config=TaskConfig, result=Result, schedule=templates.${template}.schedule, run=run)
`
}

/**
 * A custom schedule that wraps the range or the tranco template (key `call:0`). It can slow the stream down, catch
 * template errors in user code, and fail after a number of items with Fatal, an ordinary exception or an analysis
 * config above the size limit.
 */
const WRAP_TASK = `"""Generated by the e2e runtime specs: a custom schedule that wraps a template proxy."""

import time
from collections.abc import Iterator
from typing import Literal

from pydantic import BaseModel, Field

import scantor
from scantor import templates


class ScanConfig(scantor.Config):
    source: Literal["range", "tranco"] = Field(default="range", description="The wrapped template.")
    start: int = 0
    end: int = 10
    step: int = 1
    tranco_list: str = Field(default="latest", description="tranco: the list.")
    offset: int = Field(default=0, ge=0)
    limit: int = Field(default=10, ge=1)
    item_delay: float = Field(default=0, ge=0, le=10, description="Pause before yielding each item.")
    catch: bool = Field(default=False, description="Catch template errors and yield one item that describes them.")
    fail_after: int = Field(default=-1, ge=-1, description="Fail once this many items were yielded; -1 never fails.")
    fail_with: Literal["fatal", "error", "big_config"] = "fatal"
    config_bytes: int = Field(default=70000, ge=1, le=1000000, description="big_config: size of the note.")


class AnalysisConfig(scantor.Config):
    value: int
    domain: str = ""
    note: str = ""


class Result(BaseModel):
    value: int
    domain: str
    note: str


def items(ctx: scantor.Context, scan_config: ScanConfig) -> Iterator[AnalysisConfig]:
    if scan_config.source == "tranco":
        wanted = {"list": scan_config.tranco_list, "offset": scan_config.offset, "limit": scan_config.limit}
        for item in templates.tranco.schedule(ctx, wanted):
            yield AnalysisConfig(value=item.rank, domain=item.domain)
    else:
        wanted = {"start": scan_config.start, "end": scan_config.end, "step": scan_config.step}
        for item in templates.range.schedule(ctx, wanted):
            yield AnalysisConfig(value=item.value)


def schedule(ctx: scantor.Context, scan_config: ScanConfig, task_config: scantor.Empty) -> Iterator[AnalysisConfig]:
    yielded = 0
    try:
        for item in items(ctx, scan_config):
            if yielded == scan_config.fail_after:
                if scan_config.fail_with == "fatal":
                    raise scantor.Fatal(f"generated fatal error after {yielded} items")
                if scan_config.fail_with == "error":
                    raise RuntimeError(f"generated exception after {yielded} items")
                item = AnalysisConfig(value=item.value, note="x" * scan_config.config_bytes)
            if scan_config.item_delay > 0:
                time.sleep(scan_config.item_delay)
            yield item
            yielded += 1
    except scantor.ScantorError as exc:
        if not scan_config.catch:
            raise
        yield AnalysisConfig(value=-1, note=f"{exc.type}|{exc.retryable}|{exc.message}")


def run(ctx: scantor.Context, analysis_config: AnalysisConfig, task_config: scantor.Empty) -> Result:
    return Result(value=analysis_config.value, domain=analysis_config.domain, note=analysis_config.note[:100])


task = scantor.Task(scan_config=ScanConfig, analysis_config=AnalysisConfig, result=Result, schedule=schedule, run=run)
`

/** Modes of the probe task (task config `mode`, and `others` for the iterations not listed in `iterations`). */
export type ProbeMode =
  | 'ok'
  | 'sleep'
  | 'hang'
  | 'hang_children'
  | 'exit'
  | 'flaky'
  | 'logs'
  | 'big_error'
  | 'invalid_result'
  | 'invalid_codes'
  | 'files'
  | 'flaky_files'
  | 'too_many_files'
  | 'big_file'

/** The task config of the probe task. */
export interface ProbeConfig {
  mode?: ProbeMode
  /** the mode of the iterations not listed in `iterations` (default ok) */
  others?: ProbeMode
  /** iterations that use `mode`; omitted = all */
  iterations?: number[]
  /** > 0: the mode applies only to attempts 1 … fail_attempts, later attempts succeed (logs: only `fail`) */
  fail_attempts?: number
  /** sleep: seconds (cancellable) */
  seconds?: number
  /** logs: stdout bytes; big_error: message characters (é); files and too_many_files: files */
  count?: number
  /** big_file: size of the sparse file */
  bytes?: number
  /** invalid_result and invalid_codes: invalid list entries */
  issues?: number
  /** catch file errors and report them in the result note */
  catch?: boolean
  /** logs: fail after logging */
  fail?: boolean
}

/**
 * The probe: the template repeat unwrapped (scan config `times`), and a run that ends the way the task config says.
 * Every result carries the connector's pid and the attempt, and every run logs `probe pid=<pid> attempt=<n>` first,
 * so tests can follow process recycling, also across failed attempts.
 */
const PROBE_TASK = `"""Generated by the e2e runtime specs: a run that ends in every documented way, chosen by the task config."""

import asyncio
import os
import subprocess
import sys
import time
from typing import Annotated, Literal, cast

from pydantic import BaseModel, Field, StringConstraints

import scantor
from scantor import templates

Mode = Literal[
    "ok",
    "sleep",
    "hang",
    "hang_children",
    "exit",
    "flaky",
    "logs",
    "big_error",
    "invalid_result",
    "invalid_codes",
    "files",
    "flaky_files",
    "too_many_files",
    "big_file",
]


class TaskConfig(scantor.Config):
    mode: Mode = "ok"
    others: Mode = Field(default="ok", description="The mode of the iterations not listed in iterations.")
    iterations: list[int] | None = Field(default=None, description="Iterations that use mode; null = all.")
    fail_attempts: int = Field(default=0, ge=0, le=20, description="> 0: mode applies only to these first attempts.")
    seconds: float = Field(default=0, ge=0, le=3600, description="sleep: duration (cancellable).")
    count: int = Field(default=0, ge=0, le=1_000_000, description="Bytes or files, depending on the mode.")
    bytes: int = Field(default=0, ge=0, le=4_294_967_296, description="big_file: size of the sparse file.")
    issues: int = Field(default=0, ge=0, le=100_000, description="invalid_result: number of invalid entries.")
    catch: bool = Field(default=False, description="Catch file errors and report them in the result note.")
    fail: bool = Field(default=False, description="logs: fail after logging (in the first fail_attempts attempts).")


# A pattern whose validation message ("String should match pattern '…'") is longer than the connector keeps of an
# issue message (300 characters): invalid_codes produces validation details far above their 4 KiB bound.
LONG_PATTERN = "^(?:" + "|".join(f"code-{n:02d}-{'x' * 20}" for n in range(12)) + ")$"
Code = Annotated[str, StringConstraints(pattern=LONG_PATTERN)]


class Nested(BaseModel):
    file: scantor.FileRef | None
    more: list[scantor.FileRef]


class Result(BaseModel):
    iteration: int
    pid: int
    attempt: int
    files: list[scantor.FileRef]
    nested: Nested
    note: str
    codes: list[Code] = []


def put_files(ctx: scantor.Context, count: int, prefix: str) -> list[scantor.FileRef]:
    return [ctx.files.put(f"{prefix}-{n}.txt", f"{prefix} {n}\\n", "text/plain") for n in range(count)]


async def run(
    ctx: scantor.Context, analysis_config: templates.repeat.AnalysisConfig, task_config: TaskConfig
) -> Result:
    iteration = analysis_config.iteration
    ctx.log("info", "probe", pid=os.getpid(), attempt=ctx.attempt)
    listed = task_config.iterations is None or iteration in task_config.iterations
    mode = task_config.mode if listed else task_config.others
    # logs and flaky_files apply fail_attempts themselves; every other mode succeeds after them
    if task_config.fail_attempts > 0 and ctx.attempt > task_config.fail_attempts and mode not in ("logs", "flaky_files"):
        mode = "ok"
    result = Result(
        iteration=iteration,
        pid=os.getpid(),
        attempt=ctx.attempt,
        files=[],
        nested=Nested(file=None, more=[]),
        note="",
    )
    match mode:
        case "sleep":
            await asyncio.sleep(task_config.seconds)
        case "hang":
            time.sleep(3600)
        case "hang_children":
            children = [subprocess.Popen(["sleep", "3600"]) for _ in range(2)]
            ctx.log("info", "children started", pids=",".join(str(child.pid) for child in children))
            time.sleep(3600)
        case "exit":
            os._exit(3)
        case "flaky":
            raise RuntimeError(f"probe failure in attempt {ctx.attempt}")
        case "logs":
            print("o" * task_config.count, flush=True)
            # stdout, stderr and ctx.log travel on separate pipes: a pause keeps their order in the log tail
            await asyncio.sleep(0.5)
            print("stderr line", file=sys.stderr, flush=True)
            ctx.log("warning", "probe log", key="value", n=7)
            await asyncio.sleep(0.5)
            if task_config.fail and (task_config.fail_attempts == 0 or ctx.attempt <= task_config.fail_attempts):
                raise RuntimeError(f"probe failure in attempt {ctx.attempt}")
        case "big_error":
            # two bytes per character in UTF-8: the bounds are bytes, the connector's own limits characters
            raise RuntimeError("é" * task_config.count)
        case "invalid_result":
            invalid = [{"id": n} for n in range(task_config.issues)]
            return cast(Result, {**result.model_dump(), "files": invalid})
        case "invalid_codes":
            return cast(Result, {**result.model_dump(), "codes": [f"bad-{n}" for n in range(task_config.issues)]})
        case "files":
            result.files = put_files(ctx, task_config.count, "file")
            result.nested = Nested(
                file=ctx.files.put("nested.bin", b"nested"),
                more=[ctx.files.put("more-0.json", '{"n": 0}', "application/json")],
            )
        case "flaky_files":
            result.files = [ctx.files.put(f"attempt-{ctx.attempt}.txt", f"attempt {ctx.attempt}\\n", "text/plain")]
            if task_config.fail_attempts == 0 or ctx.attempt <= task_config.fail_attempts:
                raise RuntimeError("probe failure after storing a file")
        case "too_many_files":
            try:
                result.files = put_files(ctx, task_config.count, "many")
            except scantor.ScantorError as exc:
                if not task_config.catch:
                    raise
                result.note = f"{exc.type}|{exc.retryable}|{exc.message}"
        case "big_file":
            path = ctx.tmp_dir / "sparse.bin"
            with path.open("wb") as handle:
                handle.truncate(task_config.bytes)
            try:
                result.files = [ctx.files.put("sparse.bin", path)]
            except scantor.ScantorError as exc:
                if not task_config.catch:
                    raise
                result.note = f"{exc.type}|{exc.retryable}|{exc.message}"
        case _:
            pass
    return result


task = scantor.Task(task_config=TaskConfig, result=Result, schedule=templates.repeat.schedule, run=run)
`

/**
 * A task whose module exits while it is imported in a worker: connector processes die before `ready`, so the
 * runtime gives up after its spawn retries and the worker container exits 1 (a crash loop). Describe and check run
 * with `--network none` (no route in the main routing table), which is how the module tells them apart and stays
 * publishable.
 */
const CRASHLOOP_TASK = `"""Generated by the e2e runtime specs: the module exits at import time in worker containers."""

import sys

from pydantic import BaseModel

import scantor


def has_network() -> bool:
    # describe and check run with --network none: /proc/net/route then lists no route at all
    with open("/proc/net/route", encoding="utf-8") as routes:
        return len(routes.read().splitlines()) > 1


if has_network():
    print("crashloop: refusing to start in a worker", file=sys.stderr, flush=True)
    sys.exit(3)


class Result(BaseModel):
    ok: bool


def run(ctx: scantor.Context, analysis_config: scantor.Empty, task_config: scantor.Empty) -> Result:
    return Result(ok=True)


task = scantor.Task(result=Result, run=run)
`

/** A task with `defaults.privileged: true` whose run reports the capabilities it got. */
const PRIVILEGED_TASK = `"""Generated by the e2e runtime specs: a privileged task that reports whether it runs privileged."""

import os

from pydantic import BaseModel

import scantor


class Result(BaseModel):
    cap_eff: str
    dind: bool


def run(ctx: scantor.Context, analysis_config: scantor.Empty, task_config: scantor.Empty) -> Result:
    cap_eff = ""
    with open("/proc/self/status", encoding="utf-8") as status:
        for line in status:
            if line.startswith("CapEff:"):
                cap_eff = line.split(":", 1)[1].strip()
    return Result(cap_eff=cap_eff, dind=os.environ.get("SCANTOR_DIND") == "1")


task = scantor.Task(result=Result, run=run)
`

export type GeneratedTaskKind = `tpl-${UnwrappedTemplate}` | 'wrap' | 'probe' | 'crashloop' | 'privileged' | 'outcomes-js' | 'outcomes-go'

/**
 * The outcomes of a run in JavaScript and Go (the template repeat unwrapped): iteration 0 raises Fatal, 1 Retry with a
 * 1 s delay, 2 an ordinary error, 3 returns a result its model rejects, 4 panics (Go) or succeeds (JavaScript), the
 * rest succeed. Python's outcomes come from the `throws` example and the probe.
 */
const OUTCOMES_JS = `// @ts-check
// Generated by the e2e runtime specs: every outcome of a run, chosen by the iteration.
import { defineTask, Fatal, Retry, z } from "@scantor/connector";
import { repeat } from "@scantor/connector/templates";

export default defineTask({
  result: z.object({ iteration: z.number().int().min(0) }),
  schedule: repeat.schedule,
  async run(ctx, analysisConfig) {
    switch (analysisConfig.iteration) {
      case 0:
        throw new Fatal("generated fatal error");
      case 1:
        throw new Retry("generated retry", 1000);
      case 2:
        throw new Error("generated exception");
      case 3:
        return { iteration: -1 };
      default:
        return { iteration: analysisConfig.iteration };
    }
  },
});
`

const OUTCOMES_GO = `// Package main is generated by the e2e runtime specs: every outcome of a run, chosen by the iteration.
package main

import (
	"errors"
	"time"

	scantor "github.com/lonetis/scantor/connectors/go"
	"github.com/lonetis/scantor/connectors/go/templates/repeat"
)

// Result echoes the iteration.
type Result struct {
	Iteration int64 \`json:"iteration" jsonschema:"minimum=0"\`
}

func run(ctx scantor.Context, ac repeat.AnalysisConfig, _ scantor.Empty) (Result, error) {
	switch ac.Iteration {
	case 0:
		return Result{}, scantor.Fatal("generated fatal error")
	case 1:
		return Result{}, scantor.Retry("generated retry", time.Second)
	case 2:
		return Result{}, errors.New("generated exception")
	case 3:
		return Result{Iteration: -1}, nil
	case 4:
		panic("generated panic")
	}
	return Result{Iteration: ac.Iteration}, nil
}

func main() { scantor.Serve(repeat.Schedule, run) }
`

/** The files of a generated JavaScript or Go task besides the manifest (dependencies as the examples have them). */
async function languageFiles(kind: 'outcomes-js' | 'outcomes-go'): Promise<Record<string, string>> {
  if (kind === 'outcomes-js') {
    const power = exampleTaskDir('power')
    return {
      Dockerfile: await readFile(join(power, 'Dockerfile'), 'utf8'),
      '.dockerignore': 'node_modules/\n.scantor/\n',
      'package.json': JSON.stringify({ name: 'outcomes', private: true, type: 'module' }, null, 2) + '\n',
      'package-lock.json': JSON.stringify({ name: 'outcomes', lockfileVersion: 3, requires: true, packages: { '': { name: 'outcomes' } } }, null, 2) + '\n',
      'jsconfig.json': await readFile(join(power, 'jsconfig.json'), 'utf8'),
      'main.js': OUTCOMES_JS,
    }
  }
  const reverseDns = exampleTaskDir('reverse-dns')
  return {
    Dockerfile: await readFile(join(reverseDns, 'Dockerfile'), 'utf8'),
    '.dockerignore': '.scantor/\n/task\n',
    'go.mod': (await readFile(join(reverseDns, 'go.mod'), 'utf8')).replace(/^module .*$/m, 'module outcomes'),
    'go.sum': await readFile(join(reverseDns, 'go.sum'), 'utf8'),
    'main.go': OUTCOMES_GO,
  }
}

function source(kind: Exclude<GeneratedTaskKind, 'outcomes-js' | 'outcomes-go'>): string {
  switch (kind) {
    case 'wrap':
      return WRAP_TASK
    case 'probe':
      return PROBE_TASK
    case 'crashloop':
      return CRASHLOOP_TASK
    case 'privileged':
      return PRIVILEGED_TASK
    default:
      return templateTask(kind.slice('tpl-'.length) as UnwrappedTemplate)
  }
}

/** Writes a generated task folder into a new temporary directory; remove it with `removeGeneratedTask`. */
export async function writeGeneratedTask(kind: GeneratedTaskKind): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), `scantor-${kind}-`))
  const language = kind === 'outcomes-js' ? 'javascript' : kind === 'outcomes-go' ? 'go' : 'python'
  const defaults = kind === 'privileged' ? 'defaults:\n  privileged: true\n' : ''
  const manifest = `scantor: 1\nname: ${kind}\nlanguage: ${language}\ndescription: "Generated by the e2e runtime specs (${kind})."\n${defaults}`
  const files: Record<string, string> =
    kind === 'outcomes-js' || kind === 'outcomes-go'
      ? await languageFiles(kind)
      : { Dockerfile: DOCKERFILE, '.dockerignore': DOCKERIGNORE, 'pyrightconfig.json': PYRIGHT, 'main.py': source(kind) }
  await Promise.all([writeFile(join(dir, 'scantor.yaml'), manifest), ...Object.entries(files).map(([name, content]) => writeFile(join(dir, name), content))])
  return dir
}

export async function removeGeneratedTask(dir: string): Promise<void> {
  await rm(dir, { recursive: true, force: true })
}

/**
 * Uploads a generated task through the `tasks` fixture (unique name, deleted at teardown) and publishes it; the
 * revision must end `ready` unless `expectState` says otherwise.
 */
export async function uploadGeneratedTask(
  tasks: TasksFixture,
  kind: GeneratedTaskKind,
  options: { expectState?: 'ready' | 'failed' } = {},
): Promise<UploadedTask> {
  const dir = await writeGeneratedTask(kind)
  try {
    return await tasks.upload(dir, { expectState: options.expectState })
  } finally {
    await removeGeneratedTask(dir)
  }
}
